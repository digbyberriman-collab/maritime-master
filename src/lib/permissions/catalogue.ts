const ACTION_ORDER = new Map<string, number>(CAPABILITY_ACTIONS.map((a, i) => [a, i]));

function parseRow([path, actions, flags = '', legacy = '']: CatalogueRow): CatalogueEntry {
  const flagSet = new Set(flags.split(' ').filter(Boolean));
  const legacyMap: Partial<Record<CapabilityAction, string>> = {};
  for (const pair of legacy.split(' ').filter(Boolean)) {
    const [action, moduleKey] = pair.split('=');
    if (isCapabilityAction(action) && moduleKey) legacyMap[action] = moduleKey;
  }
  return {
    path,
    actions: actions
      .split(' ')
      .filter(isCapabilityAction)
      .sort((a, b) => (ACTION_ORDER.get(a) ?? 0) - (ACTION_ORDER.get(b) ?? 0)),
    crewCreates: flagSet.has('crewCreates'),
    crewSigns: flagSet.has('crewSigns'),
    legacy: legacyMap,
  };
}

let index: ReadonlyMap<string, CatalogueEntry> | null = null;

function getIndex(): ReadonlyMap<string, CatalogueEntry> {
  if (!index) index = new Map(ROWS.map((row) => [row[0], parseRow(row)]));
  return index;
}

/** The catalogue subcategory at `domain.module.subcategory`, if it exists. */
export function getCatalogueEntry(path: string): CatalogueEntry | undefined {
  return getIndex().get(path);
}

/** Every catalogue subcategory, in catalogue order. */
export function listCatalogueEntries(): CatalogueEntry[] {
  return Array.from(getIndex().values());
}

/** Every capability key in the catalogue (`path.action`), in catalogue order. */
export function listCatalogueCapabilities(): string[] {
  return listCatalogueEntries().flatMap((entry) => entry.actions.map((action) => `${entry.path}.${action}`));
}
