export const NEUTRALS = ['gray', 'slate', 'zinc', 'neutral', 'stone'];
const TINT_SHADES = [50, 100, 200];
const BORDER_SHADES = [100, 200, 300];
const TEXT_SHADES = [300, 400, 500, 600, 700, 800, 900, 950];
/** Token fills that legacy code pairs with `text-white`. */
export const TOKEN_FILLS = ['primary', 'destructive', 'success', 'warning', 'info', 'critical', 'orange', 'purple', 'cyan', 'amber', 'pink', 'indigo', 'teal'];
/** Tokens whose meaning changed from "brand blue" to "neutral surface". */
export const REPURPOSED_TOKENS = ['secondary', 'accent'];
const REPLACED_ELEMENTS = 'img, canvas, svg, video, picture, iframe';

const lin = (c) => {
  const v = c / 255;
  return v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4;
};
const luminance = (hex) => {
  const h = hex.replace('#', '');
  const [r, g, b] = [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16));
  return 0.2126 * lin(r) + 0.7152 * lin(g) + 0.0722 * lin(b);
};
export const contrastRatio = (a, b) => {
  const la = luminance(a);
  const lb = luminance(b);
  return (Math.max(la, lb) + 0.05) / (Math.min(la, lb) + 0.05);
};

/** Escape a Tailwind class name for use in a CSS selector. */
export const escapeClass = (cls) => cls.replace(/([:/.[\]%])/g, '\\$1');
const sel = (cls) => `.${escapeClass(cls)}`;
const hoverSel = (cls) => `.${escapeClass(`hover:${cls}`)}:hover`;

/** Text shades of a hue that the layer remaps: 600+ always, lighter ones only if they fail AA on Deep. */
export const remappedTextShades = (hue) =>
  TEXT_SHADES.filter((shade) => shade >= 600 || contrastRatio(TAILWIND_PALETTE[hue][shade], DEEP_CARD_HEX) < 4.5);

/**
 * Build the rule list as data: [{ selectors: string[], declaration: string, comment }].
 * Kept separate from formatting so tests can inspect it.
 */
export function buildLegacyDarkCompatRules() {
  const rules = [];
  const add = (comment, selectors, declaration, scope = 'dark') => rules.push({ comment, selectors, declaration, scope });

  // Neutral surfaces.
  add(
    'White cards and panels → card surface (replaced elements keep real white)',
    [sel('bg-white')],
    'background-color: hsl(var(--card));',
  );
  for (const alpha of [50, 60, 70, 80, 90, 95]) {
    add(null, [sel(`bg-white/${alpha}`)], `background-color: hsl(var(--card) / ${alpha / 100});`);
  }
  add(
    'Light grey wells → muted',
    NEUTRALS.flatMap((n) => [50, 100].map((s) => sel(`bg-${n}-${s}`))),
    'background-color: hsl(var(--muted));',
  );
  add('Mid grey fills → secondary', NEUTRALS.map((n) => sel(`bg-${n}-200`)), 'background-color: hsl(var(--secondary));');
  add(
    'Grey hovers → accent (hover surface)',
    [hoverSel('bg-white'), ...NEUTRALS.flatMap((n) => [50, 100, 200].map((s) => hoverSel(`bg-${n}-${s}`)))],
    'background-color: hsl(var(--accent));',
  );

  // Neutral text.
  add(
    'Dark ink → foreground',
    [sel('text-black'), ...NEUTRALS.flatMap((n) => [800, 900, 950].map((s) => sel(`text-${n}-${s}`)))],
    'color: hsl(var(--foreground));',
  );
  add(
    'Grey secondary text → muted-foreground',
    NEUTRALS.flatMap((n) => [400, 500, 600, 700].map((s) => sel(`text-${n}-${s}`))),
    'color: hsl(var(--muted-foreground));',
  );
  add(
    'Grey hover text → foreground',
    NEUTRALS.flatMap((n) => [600, 700, 800, 900].map((s) => hoverSel(`text-${n}-${s}`))),
    'color: hsl(var(--foreground));',
  );

  // Neutral borders and dividers.
  add(
    'Light borders → border',
    [
      ...NEUTRALS.flatMap((n) => BORDER_SHADES.map((s) => sel(`border-${n}-${s}`))),
      ...[5, 10, 15, 20].map((a) => sel(`border-black/${a}`)),
    ],
    'border-color: hsl(var(--border));',
  );
  // Separate rule: :is() takes the specificity of its most specific argument,
  // so the (0,3,0) divide selectors must not share a list with plain classes.
  add(
    'Light dividers → border',
    [
      ...NEUTRALS.flatMap((n) => BORDER_SHADES.map((s) => `${sel(`divide-${n}-${s}`)} > :not([hidden]) ~ :not([hidden])`)),
      ...[5, 10].map((a) => `${sel(`divide-black/${a}`)} > :not([hidden]) ~ :not([hidden])`),
    ],
    'border-color: hsl(var(--border));',
  );
  add('Solid black outlines → input-strength border', [sel('border-black')], 'border-color: hsl(var(--input));');

  // Status and decorative hues.
  for (const [hue, token] of Object.entries(HUE_TOKEN)) {
    add(
      `${hue} → ${token}`,
      TINT_SHADES.map((s) => sel(`bg-${hue}-${s}`)),
      `background-color: hsl(var(--${token}-muted));`,
    );
    add(null, TINT_SHADES.map((s) => hoverSel(`bg-${hue}-${s}`)), `background-color: hsl(var(--${token}-muted));`);
    add(null, remappedTextShades(hue).map((s) => sel(`text-${hue}-${s}`)), `color: hsl(var(--${token}));`);
    add(null, [600, 700, 800, 900].map((s) => hoverSel(`text-${hue}-${s}`)), `color: hsl(var(--${token}));`);
    add(null, BORDER_SHADES.map((s) => sel(`border-${hue}-${s}`)), `border-color: hsl(var(--${token}) / 0.35);`);
  }

  // White text on a token fill: 2.5:1 on Signal and the dark status fills.
  // On dark every solid fill carries its Abyss `-foreground` (gap/10 A.2).
  for (const fill of TOKEN_FILLS) {
    add(
      fill === TOKEN_FILLS[0] ? 'White text on token fills → the fill\'s foreground' : null,
      [`${sel(`bg-${fill}`)}${sel('text-white')}`],
      `color: hsl(var(--${fill}-foreground));`,
    );
  }

  // `secondary` and `accent` used to be bright blue and are neutral surfaces
  // now, so they are never a text or border colour. The call sites moved to
  // primary/amber at Phase 0 integration and the layer no longer patches them;
  // src/test/design/legacyDarkCompat.test.ts keeps them from coming back.

  return rules;
}

const scopeSelectors = ({ selectors, declaration, scope }) => {
  const notReplaced = `:where(:not(${REPLACED_ELEMENTS}))`;
  const isBgWhite = selectors.length === 1 && selectors[0] === sel('bg-white');
  const prefix = scope === 'all' ? '' : ':where(.dark) ';
  return `${prefix}:is(${selectors.join(', ')})${isBgWhite ? notReplaced : ''} { ${declaration} }`;
};

/** The full CSS block, markers included, exactly as it appears in src/index.css. */
export function buildLegacyDarkCompatCss() {
  const body = buildLegacyDarkCompatRules()
    .map((r) => `${r.comment ? `/* ${r.comment} */\n` : ''}${scopeSelectors(r)}`)
    .join('\n');
  return `${BLOCK_START}\n${body}\n${BLOCK_END}`;
}

/** Extract the current block (markers included) from a CSS source, or null. */
export function extractLegacyDarkCompatBlock(css) {
  const start = css.indexOf(BLOCK_START);
  const end = css.indexOf(BLOCK_END);
  if (start === -1 || end === -1 || end < start) return null;
  return css.slice(start, end + BLOCK_END.length);
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const cssPath = resolve(dirname(fileURLToPath(import.meta.url)), '../../src/index.css');
  const css = readFileSync(cssPath, 'utf8');
  const current = extractLegacyDarkCompatBlock(css);
  const next = buildLegacyDarkCompatCss();
  if (process.argv.includes('--write')) {
    if (current === null) {
      console.error('Markers not found in src/index.css; add them first.');
      process.exit(1);
    }
    writeFileSync(cssPath, css.replace(current, next));
    console.log('legacy dark compat block written.');
  } else if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('legacy dark compat block is stale; run with --write.');
      process.exit(1);
    }
    console.log('legacy dark compat block is up to date.');
  } else {
    process.stdout.write(`${next}\n`);
  }
}
