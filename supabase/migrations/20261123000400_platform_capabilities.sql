-- ---------------------------------------------------------------- legacy admin and ranks

-- Today's admin rule (the adaptor's full access + RBAC settings admin, and
-- the admin-actions gate): an active user whose legacy profile role is dpa
-- or shore_management, or with an active, unexpired user_roles dpa /
-- superadmin row of their own company (or of no company), or an active,
-- in-date RBAC role superadmin / dpa, or RBAC settings admin.
CREATE OR REPLACE FUNCTION public.legacy_user_admin(_user_id uuid)
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT _user_id IS NOT NULL
     AND public.user_is_active(_user_id)
     AND (
       EXISTS (SELECT 1 FROM public.profiles AS p WHERE p.user_id = _user_id AND p.role::text IN ('dpa', 'shore_management'))
       OR EXISTS (
         SELECT 1
         FROM public.user_roles AS ur
         JOIN public.profiles AS p ON p.user_id = ur.user_id
         WHERE ur.user_id = _user_id
           AND ur.is_active = true
           AND ur.role::text IN ('dpa', 'superadmin')
           AND (ur.expires_at IS NULL OR ur.expires_at > now())
           AND (ur.company_id IS NULL OR ur.company_id = p.company_id))
       OR EXISTS (
         SELECT 1
         FROM public.rbac_user_roles AS r
         JOIN public.roles AS ro ON ro.id = r.role_id
         WHERE r.user_id = _user_id
           AND r.is_active = true
           AND (r.valid_until IS NULL OR r.valid_until > now())
           AND ro.name IN ('superadmin', 'dpa'))
       OR public.user_has_permission(_user_id, 'settings', 'admin'::public.permission_level, NULL)
     )
$$;

-- Role ranks for the no-self-escalation rules of file 8 (an admin never
-- grants a role ranked above their own).
CREATE OR REPLACE FUNCTION public.role_rank(_role_name text)
RETURNS integer
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
SET search_path = public
AS $$
  SELECT CASE _role_name
    WHEN 'superadmin' THEN 100
    WHEN 'dpa' THEN 90
    WHEN 'fleet_master' THEN 80
    WHEN 'captain' THEN 60
    WHEN 'purser' THEN 50
    WHEN 'chief_officer' THEN 50
    WHEN 'chief_engineer' THEN 50
    WHEN 'hod' THEN 40
    WHEN 'officer' THEN 30
    WHEN 'auditor' THEN 20
    WHEN 'employer_api' THEN 20
    WHEN 'crew' THEN 10
    ELSE 0
  END
$$;

-- The highest rank a user holds: active, in-date RBAC roles and the legacy
-- profile role (dpa 90, shore_management 80, master 60, chief officer /
-- chief engineer 50, crew 10). 0 for an inactive or unknown user.
CREATE OR REPLACE FUNCTION public.user_role_rank(_user_id uuid)
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT CASE WHEN NOT public.user_is_active(_user_id) THEN 0 ELSE coalesce(greatest(
    (SELECT max(public.role_rank(ro.name))
       FROM public.rbac_user_roles AS r
       JOIN public.roles AS ro ON ro.id = r.role_id
      WHERE r.user_id = _user_id
        AND r.is_active = true
        AND (r.valid_until IS NULL OR r.valid_until > now())),
    (SELECT CASE p.role::text
              WHEN 'dpa' THEN 90
              WHEN 'shore_management' THEN 80
              WHEN 'master' THEN 60
              WHEN 'chief_officer' THEN 50
              WHEN 'chief_engineer' THEN 50
              WHEN 'crew' THEN 10
              ELSE 0
            END
       FROM public.profiles AS p
      WHERE p.user_id = _user_id)
  ), 0) END
$$;

-- ---------------------------------------------------------------- capabilities

-- The rules above for any user (definers and triggers: set_membership_status,
-- notification recipients, the profile guard). False when the user is NULL
-- or inactive, the company is NULL or not the user's profile company, the
-- vessel (when given) is not a vessel of that company, or the key is not
-- one of the seven admin keys or the crew keys below.
--
-- Crew keys (Phase 3 wave 1, platform prep PP1; X1 spec §5). Each answers
-- what the client adaptor's resolveCapability() answers for the same
-- access state (D-04; src/lib/permissions/adaptor.ts, catalogue.ts), and
-- supabase/tests/fixtures/capability-cases.json (generated from that
-- adaptor) holds the parity cases. On top of the adaptor, which sees no
-- vessel, a given vessel must be in reach (reach_vessel_for); with no
-- vessel the answer is the company-level one (no reach part), as for the
-- admin keys: 'anywhere in the company', so a vessel-scope permission of a
-- role bound to one vessel counts. A definer that changes something for
-- every vessel of the company asks has_company_capability_for instead
-- (D-376), which counts only what holds company-wide. The rules live in
-- capability_crew_key (the one key table); has_capability_for calls it
-- with the company-wide flag off. The access state, read as the client's
-- permissionsStore loads it:
--   RBAC roles     active, in-date rbac_user_roles role names
--                  (get_user_roles_full)
--   permissions    module_key:level of the active, in-date RBAC role
--                  permission rows and the granted, in-date overrides
--                  (get_user_rbac_permissions). A vessel-scoped row of a
--                  role bound to a vessel counts only on that vessel or
--                  with no vessel (the user_has_permission() vessel rule;
--                  narrower than the client, fail closed)
--   legacy role    profiles.role
-- and the rules (requiredLevel, ruleSatisfied, canAccessModule):
--   view_own       an active member who reaches the vessel; the definer
--                  checks the subject (adaptor: signed in)
--   level          view / export -> view; create -> edit (self for
--                  hours_of_rest, crewCreates); sign -> edit (self for
--                  familiarisation, crewSigns); edit / assign / approve
--                  -> edit; final_approve / admin -> admin
--   legacy flag    a catalogue legacy module row at view grants the action;
--                  without it an approval needs the rule at admin
--   rbac rule      full access (RBAC superadmin / dpa, legacy dpa /
--                  shore_management), or the module's permission at the
--                  level (self -> view), or for self / view the nav check:
--                  RBAC superadmin / dpa / fleet_master, the nav module's
--                  view permission, or a legacy role of the nav's list
--                  (crew: dpa, shore_management, master, chief_officer;
--                  development: none)
--   domain rule    hr_can_view / hr_can_edit / hr_can_admin,
--                  medical_can_view / _edit / _admin at the level
--
--   vessel.crew.{crew_list, crew_profiles, crew_scheduling,
--     crew_assignments, hours_of_rest}   RBAC crew_roster, nav crew
--   vessel.crew.{crew_certificates, expiry_alerts, crew_compliance}
--                                        RBAC crew_certificates, nav crew
--   vessel.crew.familiarisation          RBAC training, nav development
--   hris.leave_rotation.leave_requests.approve, hris.employee_records.
--     contracts_employment.{view, edit}  domain hr
--   health.personnel_medical.crew_medical_records.view   domain medical
--   legacy flags: crew_list.view crew.see_crew_list; crew_profiles.view
--     crew.view_crew_profiles, .edit crew.edit_crew_profiles;
--     crew_scheduling.view crew.view_scheduling; hours_of_rest.approve
--     crew.approve_hours_of_rest; leave_requests.approve crew.approve_leave;
--     contracts_employment.view crew.access_employment_records;
--     crew_medical_records.view crew.view_medical
-- The crew-key core (PP1; D-376): the crew, HR and health keys for any
-- user, with the key table of has_capability_for (its one definition). In
-- the default mode (p_company_wide false) it answers exactly what
-- has_capability_for answers for these keys; with p_vessel_id NULL that is
-- the 'anywhere in the company' read answer, where a vessel-scoped
-- permission of a role bound to one vessel counts. In the company-wide mode
-- (has_company_capability_for, p_vessel_id NULL) it counts only what holds
-- for the whole company: the full-access paths (RBAC superadmin / dpa,
-- legacy dpa / shore_management), RBAC permission rows of a role bound to no
-- vessel or of a scope other than 'vessel', granted overrides bound to no
-- vessel, the legacy flags on those rows, and the HR / medical domain
-- helpers; never the nav fallback. Internal (service role; definers).
CREATE OR REPLACE FUNCTION public.capability_crew_key(_user_id uuid, p_key text, p_company_id uuid, p_vessel_id uuid, p_company_wide boolean)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_company uuid;
  v_role text;
  v_wide boolean := coalesce(p_company_wide, false);
  v_action text;
  v_path text;
  v_module text;
  v_nav text;
  v_domain text;
  v_flag text;
  v_need text;
  v_roles text[];
  v_perms text[];
  v_want text[];
  v_nav_ok boolean;
BEGIN
  IF _user_id IS NULL OR p_company_id IS NULL OR p_key IS NULL OR (v_wide AND p_vessel_id IS NOT NULL) THEN
    RETURN false;
  END IF;
  IF p_key NOT IN (
    'vessel.crew.crew_list.view', 'vessel.crew.crew_list.export',
    'vessel.crew.crew_profiles.view', 'vessel.crew.crew_profiles.view_own', 'vessel.crew.crew_profiles.create', 'vessel.crew.crew_profiles.edit',
    'vessel.crew.crew_certificates.view', 'vessel.crew.crew_certificates.view_own', 'vessel.crew.crew_certificates.create',
    'vessel.crew.crew_certificates.edit', 'vessel.crew.crew_certificates.approve',
    'vessel.crew.expiry_alerts.edit',
    'vessel.crew.crew_compliance.view', 'vessel.crew.crew_compliance.admin',
    'vessel.crew.crew_assignments.view', 'vessel.crew.crew_assignments.assign', 'vessel.crew.crew_assignments.approve',
    'vessel.crew.crew_scheduling.view', 'vessel.crew.crew_scheduling.edit',
    'vessel.crew.hours_of_rest.view_own', 'vessel.crew.hours_of_rest.view', 'vessel.crew.hours_of_rest.create', 'vessel.crew.hours_of_rest.edit',
    'vessel.crew.hours_of_rest.approve', 'vessel.crew.hours_of_rest.final_approve', 'vessel.crew.hours_of_rest.export',
    'vessel.crew.familiarisation.view_own', 'vessel.crew.familiarisation.view', 'vessel.crew.familiarisation.create',
    'vessel.crew.familiarisation.edit', 'vessel.crew.familiarisation.sign', 'vessel.crew.familiarisation.approve',
    'hris.leave_rotation.leave_requests.approve',
    'hris.employee_records.contracts_employment.view', 'hris.employee_records.contracts_employment.edit',
    'health.personnel_medical.crew_medical_records.view'
  ) THEN
    RETURN false;
  END IF;
  IF NOT public.user_is_active(_user_id) THEN
    RETURN false;
  END IF;
  SELECT p.company_id, p.role::text INTO v_company, v_role FROM public.profiles AS p WHERE p.user_id = _user_id;
  IF v_company IS DISTINCT FROM p_company_id THEN
    RETURN false;
  END IF;
  IF p_vessel_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.vessels AS v WHERE v.id = p_vessel_id AND v.company_id = p_company_id) THEN
    RETURN false;
  END IF;
  IF p_vessel_id IS NOT NULL AND NOT public.reach_vessel_for(_user_id, p_vessel_id) THEN
    RETURN false;
  END IF;
  v_action := substring(p_key FROM '[a-z_]+$');
  v_path := left(p_key, length(p_key) - length(v_action) - 1);
  IF v_action = 'view_own' THEN
    RETURN true;  -- an active member who reaches the vessel; the definer checks the subject
  END IF;

  CASE v_path
    WHEN 'vessel.crew.crew_list' THEN
      v_module := 'crew_roster'; v_nav := 'crew';
      v_flag := CASE v_action WHEN 'view' THEN 'crew.see_crew_list' END;
    WHEN 'vessel.crew.crew_profiles' THEN
      v_module := 'crew_roster'; v_nav := 'crew';
      v_flag := CASE v_action WHEN 'view' THEN 'crew.view_crew_profiles' WHEN 'edit' THEN 'crew.edit_crew_profiles' END;
    WHEN 'vessel.crew.crew_scheduling' THEN
      v_module := 'crew_roster'; v_nav := 'crew';
      v_flag := CASE v_action WHEN 'view' THEN 'crew.view_scheduling' END;
    WHEN 'vessel.crew.crew_assignments' THEN
      v_module := 'crew_roster'; v_nav := 'crew';
    WHEN 'vessel.crew.hours_of_rest' THEN
      v_module := 'crew_roster'; v_nav := 'crew';
      v_flag := CASE v_action WHEN 'approve' THEN 'crew.approve_hours_of_rest' END;
    WHEN 'vessel.crew.crew_certificates', 'vessel.crew.expiry_alerts', 'vessel.crew.crew_compliance' THEN
      v_module := 'crew_certificates'; v_nav := 'crew';
    WHEN 'vessel.crew.familiarisation' THEN
      v_module := 'training'; v_nav := 'development';
    WHEN 'hris.leave_rotation.leave_requests' THEN
      v_domain := 'hr';
      v_flag := CASE v_action WHEN 'approve' THEN 'crew.approve_leave' END;
    WHEN 'hris.employee_records.contracts_employment' THEN
      v_domain := 'hr';
      v_flag := CASE v_action WHEN 'view' THEN 'crew.access_employment_records' END;
    WHEN 'health.personnel_medical.crew_medical_records' THEN
      v_domain := 'medical';
      v_flag := CASE v_action WHEN 'view' THEN 'crew.view_medical' END;
    ELSE
      RETURN false;
  END CASE;

  -- requiredLevel(): the catalogue's crewCreates (hours_of_rest) and crewSigns (familiarisation)
  v_need := CASE
    WHEN v_action IN ('view', 'export') THEN 'view'
    WHEN v_action = 'create' THEN CASE WHEN v_path = 'vessel.crew.hours_of_rest' THEN 'self' ELSE 'edit' END
    WHEN v_action = 'sign' THEN CASE WHEN v_path = 'vessel.crew.familiarisation' THEN 'self' ELSE 'edit' END
    WHEN v_action IN ('edit', 'assign', 'approve') THEN 'edit'
    ELSE 'admin'
  END;

  SELECT coalesce(array_agg(DISTINCT lower(ro.name)), ARRAY[]::text[]) INTO v_roles
  FROM public.rbac_user_roles AS r
  JOIN public.roles AS ro ON ro.id = r.role_id
  WHERE r.user_id = _user_id
    AND r.is_active = true
    AND (r.valid_until IS NULL OR r.valid_until > now());

  -- Company-wide mode (D-376): a vessel-scoped permission of a role bound
  -- to one vessel, and an override bound to a vessel, never count.
  SELECT coalesce(array_agg(DISTINCT x.module_key || ':' || x.permission), ARRAY[]::text[]) INTO v_perms
  FROM (
    SELECT rp.module_key, rp.permission::text AS permission
    FROM public.rbac_user_roles AS r
    JOIN public.role_permissions AS rp ON rp.role_id = r.role_id
    WHERE r.user_id = _user_id
      AND r.is_active = true
      AND (r.valid_until IS NULL OR r.valid_until > now())
      AND CASE WHEN v_wide THEN (r.vessel_id IS NULL OR rp.scope IS DISTINCT FROM 'vessel')
               ELSE (rp.scope IS DISTINCT FROM 'vessel' OR r.vessel_id IS NULL OR p_vessel_id IS NULL OR r.vessel_id = p_vessel_id) END
    UNION ALL
    SELECT o.module_key, o.permission::text
    FROM public.user_permission_overrides AS o
    WHERE o.user_id = _user_id
      AND o.is_granted = true
      AND (o.valid_until IS NULL OR o.valid_until > now())
      AND (NOT v_wide OR o.vessel_id IS NULL)
  ) AS x;

  -- The catalogue legacy flag grants the action; without it an approval needs the rule at admin.
  IF v_flag IS NOT NULL THEN
    IF v_perms && ARRAY[v_flag || ':view', v_flag || ':edit', v_flag || ':admin'] THEN
      RETURN true;
    END IF;
    IF v_action IN ('approve', 'final_approve') THEN
      v_need := 'admin';
    END IF;
  END IF;

  IF v_domain = 'hr' THEN
    RETURN coalesce(CASE v_need
      WHEN 'view' THEN public.hr_can_view(_user_id)
      WHEN 'edit' THEN public.hr_can_edit(_user_id)
      WHEN 'admin' THEN public.hr_can_admin(_user_id)
      ELSE false
    END, false);
  END IF;
  IF v_domain = 'medical' THEN
    RETURN coalesce(CASE v_need
      WHEN 'view' THEN public.medical_can_view(_user_id)
      WHEN 'edit' THEN public.medical_can_edit(_user_id)
      WHEN 'admin' THEN public.medical_can_admin(_user_id)
      ELSE false
    END, false);
  END IF;

  -- RBAC rule: full access, the module permission at the level, or (self / view) the nav check.
  IF v_roles && ARRAY['superadmin', 'dpa'] OR v_role IN ('dpa', 'shore_management') THEN
    RETURN true;
  END IF;
  v_want := CASE v_need
    WHEN 'admin' THEN ARRAY[v_module || ':admin']
    WHEN 'edit' THEN ARRAY[v_module || ':edit', v_module || ':admin']
    ELSE ARRAY[v_module || ':view', v_module || ':edit', v_module || ':admin']
  END;
  IF v_perms && v_want THEN
    RETURN true;
  END IF;
  IF v_wide OR v_need NOT IN ('self', 'view') THEN
    RETURN false;
  END IF;
  v_nav_ok := v_roles && ARRAY['superadmin', 'dpa', 'fleet_master']
    OR CASE v_nav
         WHEN 'crew' THEN v_perms && ARRAY['crew_roster:view', 'crew_roster:edit', 'crew_roster:admin']
                          OR coalesce(v_role IN ('dpa', 'shore_management', 'master', 'chief_officer'), false)
         WHEN 'development' THEN v_perms && ARRAY['training:view', 'training:edit', 'training:admin']
         ELSE false
       END;
  RETURN coalesce(v_nav_ok, false);
END;
$$;

CREATE OR REPLACE FUNCTION public.has_capability_for(_user_id uuid, p_key text, p_company_id uuid, p_vessel_id uuid DEFAULT NULL)
RETURNS boolean
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_company uuid;
  v_role text;
  v_kind text;
  v_level text;
  v_scope text;
  v_is_dpa boolean;
  v_full boolean;
  v_ua text;
  v_scope_ok boolean;
BEGIN
  IF _user_id IS NULL OR p_company_id IS NULL OR p_key IS NULL THEN
    RETURN false;
  END IF;
  -- ---------------------------------------------------------- crew keys (PP1): the one key table is the core's (D-376)
  IF p_key LIKE 'vessel.crew.%' OR p_key LIKE 'hris.%' OR p_key LIKE 'health.%' THEN
    RETURN coalesce(public.capability_crew_key(_user_id, p_key, p_company_id, p_vessel_id, false), false);
  END IF;
  IF p_key NOT IN (
    'admin.access.users_access.view', 'admin.access.users_access.assign', 'admin.access.users_access.admin',
    'admin.access.roles_permissions.admin', 'admin.access.permission_audit_log.view',
    'fleet.operations.vessels.view', 'fleet.operations.vessels.admin'
  ) THEN
    RETURN false;
  END IF;
  IF NOT public.user_is_active(_user_id) THEN
    RETURN false;
  END IF;

  SELECT p.company_id, p.role::text INTO v_company, v_role FROM public.profiles AS p WHERE p.user_id = _user_id;
  IF v_company IS DISTINCT FROM p_company_id THEN
    RETURN false;
  END IF;
  IF p_vessel_id IS NOT NULL AND NOT EXISTS (SELECT 1 FROM public.vessels AS v WHERE v.id = p_vessel_id AND v.company_id = p_company_id) THEN
    RETURN false;
  END IF;

  -- ---------------------------------------------------------- the seven admin keys
  IF p_key = 'admin.access.roles_permissions.admin' THEN
    RETURN false;  -- role definitions are global rows: platform only
  END IF;

  -- The non-legacy membership, active and in its window, if any.
  SELECT m.kind, m.users_access_level, m.vessel_scope, m.is_dpa
    INTO v_kind, v_level, v_scope, v_is_dpa
  FROM public.account_memberships AS m
  WHERE m.user_id = _user_id
    AND m.company_id = p_company_id
    AND NOT m.legacy_managed
    AND m.status = 'active'
    AND (m.valid_from IS NULL OR m.valid_from <= now())
    AND (m.valid_until IS NULL OR m.valid_until > now());

  v_full := public.legacy_user_admin(_user_id) OR coalesce(v_kind = 'owner', false);
  v_ua := CASE WHEN v_full THEN 'write' WHEN v_kind = 'admin' THEN v_level ELSE 'none' END;
  v_scope_ok := v_full OR p_vessel_id IS NULL OR public.reach_vessel_for(_user_id, p_vessel_id);

  RETURN coalesce(CASE p_key
    WHEN 'admin.access.users_access.view' THEN v_ua IN ('read', 'write') AND v_scope_ok
    WHEN 'admin.access.users_access.assign' THEN
      (v_ua = 'write' AND v_scope_ok)
      OR (v_role = 'master' AND p_vessel_id IS NOT NULL AND public.reach_vessel_for(_user_id, p_vessel_id))
    WHEN 'admin.access.users_access.admin' THEN v_ua = 'write' AND v_scope_ok
    WHEN 'admin.access.permission_audit_log.view' THEN v_full OR coalesce(v_is_dpa, false) OR v_role = 'dpa'
    WHEN 'fleet.operations.vessels.view' THEN
      public.fleet_reach_for(_user_id, p_company_id)
      OR (p_vessel_id IS NOT NULL AND public.reach_vessel_for(_user_id, p_vessel_id))
    WHEN 'fleet.operations.vessels.admin' THEN v_full OR (coalesce(v_kind = 'admin', false) AND v_scope = 'all')
    ELSE false
  END, false);
END;
$$;

